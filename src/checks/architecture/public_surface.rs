//! Small, documented public surface (project scope, Rust): how many public items does a library offer, and how many of them say what they
//! are for?
//!
//! Rule record: `MOD-001` in `rules/mod.toml`. Background: `docs/rules/mod.md`; the design is
//! `docs/superpowers/specs/2026-11-01-arc-mod-checks-design.md`, section 3.9. The reading of the public surface is the one `ARC-006` uses
//! (`api_budget.rs`): declarations reachable through `pub` modules and `pub use` leaves, plus the members of the public types.
//!
//! **What it reports.** One finding per library package that has undocumented public items, with **both counts** the design asks for
//! (the census distinction: how many *items* are public and how many *members* of them): the declarations and the public inherent functions
//! of public types that carry no documentation, the first ones with their file and line, and the size of the surface. A `#[doc(hidden)]` item is
//! in neither list. An item is documented when it has a `///` comment or a `#[doc = ..]` or `#[doc(..)]` attribute other than `hidden`.
//! Severity is **Info** for any undocumented public item and **Low** when the share without documentation reaches the figure in
//! [`PARAMS`]; the size of the surface is stated, not judged (a project that wants a ceiling declares one: `ARC-006`).
//!
//! **Not done here, and why.** The part of the design note that folds the reachability check's precision (E8) into this rule, and the
//! delegated rustc lints `unreachable_pub` and `missing_docs`: those need a build, and the `reachability` check already runs compiler
//! diagnostics; this rule reads the source with `syn`, so it sees the doc attribute of every item at once and needs no toolchain. A public
//! item that nothing uses is the `reachability` check's finding, not this one's.
//!
//! **Weak evidence by construction (medium confidence).** Syntactic: an item is public when every module above it is `pub` or it is
//! re-exported; macro-generated items, `#[path]` modules and `cfg`-gated items are not resolved; a doc comment generated by a macro
//! is not seen; trait items and enum variants are not counted as items to document; a crate with only a binary offers no library API and
//! is noted. The finding names items and counts and offers no change.
//!
//! **Known limitations / deliberate scope:** one package at a time, at `HEAD`; a file `syn` cannot parse is an error, never a smaller count.

use super::api_budget::{surface, Totals};
use crate::check::{Check, CheckContext, Network, Scope};
use crate::checks::rust_sources::read_sources;
use crate::finding::{Claim, Confidence, Finding, Location, Severity};
use std::collections::BTreeSet;

/// The check's id, as `coderipper check` and allowlist entries name it.
pub const CHECK_ID: &str = crate::rule_id::MOD_001;

/// What makes the finding Low rather than Info.
pub(crate) struct Params {
    /// The share of documentable public items without documentation, in percent, from which a finding is Low.
    pub low_share_percent: usize,
    /// The fewest documentable items the package needs for the share to count (a three-item crate with one gap is not Low).
    pub min_items_for_low: usize,
    pub source: &'static str,
}

pub(crate) const PARAMS: Params = Params {
    low_share_percent: 50,
    min_items_for_low: 20,
    source: "provisional",
};

/// Reports library packages whose public items lack documentation (see the module docs).
#[derive(Debug, Clone, Copy, Default)]
#[non_exhaustive]
pub struct PublicSurfaceCheck;

impl PublicSurfaceCheck {
    /// The check.
    pub fn new() -> Self {
        Self
    }
}

impl Check for PublicSurfaceCheck {
    fn id(&self) -> &'static str {
        CHECK_ID
    }

    fn scope(&self) -> Scope {
        Scope::Project
    }

    fn requires_rust_crate(&self) -> bool {
        true
    }

    fn network(&self) -> Network {
        Network::LocalOnly
    }

    fn run(&self, ctx: &CheckContext) -> anyhow::Result<Vec<Finding>> {
        self.run_noted(ctx).map(|(findings, _)| findings)
    }

    fn run_noted(&self, ctx: &CheckContext) -> anyhow::Result<(Vec<Finding>, Vec<String>)> {
        let (package, _) = crate::package::locate(&ctx.project_root)?;
        let files = read_sources(&package.dir)?;
        let (totals, mut notes) = surface(&files, "", &BTreeSet::new())?;
        let project = package.dir.file_name().map_or_else(
            || package.name.clone(),
            |n| n.to_string_lossy().into_owned(),
        );
        notes.push(format!(
            "MOD-001 read a public surface of {} item(s) and {} member(s); {} documentable item(s), {} without documentation",
            totals.item_count(),
            totals.members,
            totals.documented + totals.undocumented.len(),
            totals.undocumented.len()
        ));
        Ok((judge(&totals, &PARAMS, &project), notes))
    }
}

/// The finding for a package, or none when everything public is documented (or nothing is public).
pub(crate) fn judge(t: &Totals, p: &Params, project: &str) -> Vec<Finding> {
    let missing = t.undocumented.len();
    let documentable = t.documented + missing;
    if missing == 0 {
        return Vec::new();
    }
    let share = missing * 100 / documentable;
    let low = documentable >= p.min_items_for_low && share >= p.low_share_percent;
    let first = &t.undocumented[0];
    let shown = t
        .undocumented
        .iter()
        .take(8)
        .map(|u| format!("`{}` ({} at {}:{})", u.name, u.kind, u.file, u.line))
        .collect::<Vec<_>>()
        .join(", ");
    vec![Finding {
        check_id: CHECK_ID.into(),
        claim: Claim::Presence,
        severity: if low { Severity::Low } else { Severity::Info },
        confidence: Confidence::Medium,
        project: project.into(),
        location: Some(Location {
            file: first.file.clone(),
            line: u32::try_from(first.line).ok(),
        }),
        subject: Some(project.into()),
        summary: format!(
            "{missing} of {documentable} public items have no documentation ({share}%), the first at {}:{}",
            first.file, first.line
        ),
        detail: format!(
            "The public surface is {} item(s) ({}) and {} member(s) of the public types (fields, variants, trait items and inherent associated items). Of the {documentable} public declarations and public inherent functions that can carry documentation, {missing} carry none: {shown}{}. Whatever is public becomes something callers rely on; documentation turns it into a stated contract. Document the items that stay public, or narrow the visibility of those that are not part of the interface. Low from {}% of at least {} items without documentation ({}), Info below. Syntactic: macro-generated items and doc comments are not seen, and `#[doc(hidden)]` items are left out.",
            t.item_count(),
            t.items
                .iter()
                .map(|(k, n)| format!("{n} {k}"))
                .collect::<Vec<_>>()
                .join(", "),
            t.members,
            if missing > 8 { ", ..." } else { "" },
            p.low_share_percent,
            p.min_items_for_low,
            p.source
        ),
        member: None,
        positive_control: None,
    }]
}

