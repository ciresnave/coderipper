/// Every compiled-in check, in the order they run.
///
/// The list is fixed rather than loaded dynamically: there is no known need yet for a check this project's own
/// maintainers didn't write. To run your own, pass a list to [`run_checks_with`].
pub fn registered_checks() -> Vec<Box<dyn Check>> {
    builtin::BuiltinCheck::ALL
        .into_iter()
        .map(builtin::BuiltinCheck::build)
        .collect()
}

/// Run every registered check at or below the requested tier, collect and validate their
/// findings, apply the project's allowlist to them (checks return RAW findings; suppression is the
/// host's job; what an entry waives is kept in [`RunResult::waived`]), and return what is left plus one `Info` finding per allowlist
/// entry that no longer suppresses anything. A check whose `run` returns an invalid absence-claim finding is
/// dropped with an error noted in `errors`, not silently included — see `Finding::validate`.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct RunResult {
    /// The validated findings that the allowlist did not waive, plus the allowlist's own `Info` findings.
    pub findings: Vec<Finding>,
    /// What went wrong: a check that failed to run, a finding the host rejected as invalid, an unreadable allowlist.
    /// A non-empty list means the audit is incomplete, whatever `findings` says.
    pub errors: Vec<String>,
    /// How each rule that was asked for fared: clean, findings, skipped (did not apply) or could not run. This is what the
    /// coverage report's "this run" counts come from; it is empty for a result built with [`RunResult::new`].
    pub outcomes: Vec<coverage::RuleRun>,
    /// What the run has to say that is neither a finding nor an error. Rules that were not run, and why, when that is a gap
    /// (a delegated rule whose tool is not installed: `SEC-002 not run: gitleaks is not available: ...`), and what a rule that DID
    /// run set aside (`reachability: 3 dead-code candidate(s) were set aside ...`). Informational: it never fails a run.
    pub notes: Vec<String>,
    /// The findings the project's `[[allow]]` entries waived, each with its reason. They are not in `findings` and never fail a run, but
    /// a report should show them: a waiver the reader cannot see is a finding hidden.
    pub waived: Vec<Waived>,
}

impl RunResult {
    /// A result with these findings and errors: for a wrapper or a test double that must return one.
    pub fn new(findings: Vec<Finding>, errors: Vec<String>) -> Self {
        Self {
            findings,
            errors,
            outcomes: Vec::new(),
            notes: Vec::new(),
            waived: Vec::new(),
        }
    }
}

/// Which checks a run takes, by what they judge (see [`check::Unit`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum UnitFilter {
    /// Every check, whatever it judges (what `run_checks` always did).
    Any,
    /// Only the checks that judge this unit.
    Only(check::Unit),
    /// Only the checks that judge this unit AND read a Rust crate, and no other rule: a crate found below a project root that
    /// has none of its own is checked with these (see [`run_below_root`]).
    RustOnly(check::Unit),
}

/// What a `--workspace` run did, beyond its findings and errors.
#[non_exhaustive]
pub struct WorkspaceRun {
    /// Every member's findings (each marked with its [`Finding::member`](finding::Finding::member)) and every error.
    pub result: RunResult,
    /// Members analysed (a poisoned session stops the loop early).
    pub members: usize,
    /// Members whose run reported at least one error.
    pub members_with_errors: usize,
    /// The names of those members, in the order they were analysed, so a report can say which ones could not be judged (a member whose
    /// build failed asserts nothing about its code).
    pub members_failed: Vec<String>,
}

/// Runs the checks over every member of the cargo workspace containing `ctx.project_root` (the root or any member).
///
/// Checks that judge the whole repository ([`check::Unit::Repository`]) run ONCE, at the workspace root. Checks that
/// judge a package run once per member, in sorted order, inside one session checkout (see `session`), each exactly as
/// `--project <member>` runs them: the member's own `.coderipper.toml`, the same stale-entry judgement. Every finding
/// from a member carries that member's package name. An error in one member does not stop the others; a session
/// whose restore failed does (nothing is analysed in a dirty checkout). `on_member(name, i, n)` is told as each member
/// starts, so a long run can show where it is.
pub fn run_workspace(
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    on_member: &mut dyn FnMut(&str, usize, usize),
) -> WorkspaceRun {
    run_workspace_in(Profile::Classic, ctx, tier, only_check_id, on_member)
}

/// Which rules a run takes (the CLI's `--profile`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Profile {
    /// The five original checks, and the `conflict-marker` rule (a committed conflict marker is a broken file in any profile).
    Classic,
    /// `Classic`, plus the rules of the built-in language-neutral module ([`module::NeutralModule`]) and the rules delegated to
    /// installed tools ([`module::DelegatedModule`]; a tool that is not installed makes its rule a reported gap, never a
    /// failure). Those rules judge the whole repository, so a workspace run takes them once, at the workspace root.
    Extended,
    /// The language-neutral rules and the five original checks without the delegated tool rules, with a blocking floor per rule
    /// ([`portfolio_floor`]): the profile a repository's pull-request check runs.
    Portfolio,
}

/// The lowest severity at which a finding of `check_id` fails a `portfolio` run, or `None` when the rule only reports.
///
/// Blocking is for the mechanical violations the owner has ruled on: a dependency that is not a published version (`SUP-004`), a
/// committed conflict marker, a version that disagrees with itself, and a patent-index `avoid` (High, the `avoid` action). Every other
/// rule reports and never blocks until the owner rules it blocking (a lockfile, a CODEOWNERS file and a CI-protection check are
/// candidates). A rule that judges an expectation that is allowed to be incomplete while a project is under way (documentation, lint
/// suppressions, the Rust reachability and parameter analyses) stays advisory: the owner's words are that those "are not gates that
/// have to be verified before we proceed".
pub fn portfolio_floor(check_id: &str) -> Option<finding::Severity> {
    match check_id {
        "SUP-004" | "version-consistency" => Some(finding::Severity::Medium),
        "conflict-marker" => Some(finding::Severity::Low),
        "patent-index-match" => Some(finding::Severity::High),
        // only the missing licence file is High; the manifest, header and holder findings are Medium and report only
        "licence" => Some(finding::Severity::High),
        _ => None,
    }
}

impl Profile {
    /// The rule ids this profile adds to the five original checks.
    fn extra_rules(self) -> Vec<&'static str> {
        match self {
            // the one rule every profile takes: a committed conflict marker is a broken file, whatever else is checked
            Profile::Classic => vec!["conflict-marker"],
            Profile::Extended => {
                let mut ids = module::neutral_rule_ids();
                ids.extend(module::delegated_rule_ids());
                ids
            }
            Profile::Portfolio => module::neutral_rule_ids(),
        }
    }
}

/// [`run_workspace`] under a profile.
pub fn run_workspace_in(
    profile: Profile,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    on_member: &mut dyn FnMut(&str, usize, usize),
) -> WorkspaceRun {
    run_workspace_in_with_tools(
        profile,
        &ToolEnv::from_environment(),
        ctx,
        tier,
        only_check_id,
        on_member,
    )
}

/// [`run_workspace_in`] with the tools the delegated rules may use: where they are cached, which lock pins them, and whether
/// installing a missing one is allowed (see [`tools::ToolEnv`]).
pub fn run_workspace_in_with_tools(
    profile: Profile,
    tools: &ToolEnv,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    on_member: &mut dyn FnMut(&str, usize, usize),
) -> WorkspaceRun {
    run_workspace_in_with_tools_skipping(profile, tools, ctx, tier, only_check_id, &[], on_member)
}

/// [`run_workspace_in_with_tools`] without the built-in checks named in `skip` (see [`run_checks_in_with_tools_skipping`]).
pub fn run_workspace_in_with_tools_skipping(
    profile: Profile,
    tools: &ToolEnv,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    skip: &[(String, String)],
    on_member: &mut dyn FnMut(&str, usize, usize),
) -> WorkspaceRun {
    let checks = match checks_without(skip) {
        Ok(checks) => checks,
        Err(e) => {
            return WorkspaceRun {
                result: RunResult::new(Vec::new(), vec![e]),
                members: 0,
                members_with_errors: 0,
                members_failed: Vec::new(),
            }
        }
    };
    let mut run =
        run_workspace_over_in(profile, tools, &checks, ctx, tier, only_check_id, on_member);
    run.result.notes.extend(skip_notes(skip));
    redact::finish(&mut run.result);
    run
}

fn run_workspace_over_in(
    profile: Profile,
    tools: &ToolEnv,
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    on_member: &mut dyn FnMut(&str, usize, usize),
) -> WorkspaceRun {
    let failed = |message: String| WorkspaceRun {
        result: RunResult::new(Vec::new(), vec![message]),
        members: 0,
        members_with_errors: 0,
        members_failed: Vec::new(),
    };
    // before visiting any member: a wrong id would otherwise repeat its error once per member
    if let Some(problem) = check_list_problem(checks, &profile.extra_rules(), only_check_id) {
        return failed(problem);
    }
    // No crate at the root: nothing for `cargo metadata` to answer, so the single-project path decides (a gap, or the crates
    // it finds below the root, checked where they are).
    if checks.iter().any(|c| c.requires_rust_crate()) && !package::has_manifest(&ctx.project_root) {
        let (result, members, members_with_errors) = run_checks_over_in_counted(
            profile,
            tools,
            checks,
            ctx,
            tier,
            only_check_id,
            UnitFilter::Any,
        );
        return WorkspaceRun {
            result,
            members,
            members_with_errors,
            members_failed: Vec::new(),
        };
    }
    let (root, members) = match package::workspace_members(&ctx.project_root) {
        Ok(found) => found,
        Err(e) => return failed(e.to_string()),
    };

    let mut findings = Vec::new();
    let mut errors = Vec::new();
    let mut outcomes: Vec<coverage::RuleRun> = Vec::new();
    let mut notes: Vec<String> = Vec::new();
    let mut waived: Vec<Waived> = Vec::new();
    // The same allowlist file can be judged twice (a root package is both the repository's unit and a member): a stale
    // or unknown-check entry is reported once.
    let mut judged = std::collections::HashSet::new();

    let repository = run_checks_over_in(
        profile,
        tools,
        checks,
        &CheckContext {
            project_root: root.clone(),
            portfolio_root: ctx.portfolio_root.clone(),
            cargo_features: ctx.cargo_features.clone(),
        },
        tier,
        only_check_id,
        UnitFilter::Only(check::Unit::Repository),
    );
    for finding in repository.findings {
        if finding.check_id != suppression::ALLOWLIST_CHECK_ID
            || judged.insert(allowlist_key(&finding))
        {
            findings.push(finding);
        }
    }
    errors.extend(repository.errors);
    notes.extend(repository.notes);
    waived.extend(repository.waived);
    coverage::merge_runs(&mut outcomes, repository.outcomes);

    let session = match session::Session::open(&root) {
        Ok(session) => session,
        Err(e) => {
            errors.push(format!("cannot open the workspace session: {e}"));
            return WorkspaceRun {
                result: RunResult {
                    waived,
                    ..RunResult::new(findings, errors)
                },
                members: 0,
                members_with_errors: 0,
                members_failed: Vec::new(),
            };
        }
    };

    let total = members.len();
    let mut analysed = 0;
    let mut with_errors = 0;
    let mut failed_members: Vec<String> = Vec::new();
    session::with_session(&session, || {
        for (index, member) in members.iter().enumerate() {
            on_member(&member.name, index + 1, total);
            let run = run_checks_over_in(
                profile,
                tools,
                checks,
                &CheckContext {
                    project_root: member.dir.clone(),
                    portfolio_root: ctx.portfolio_root.clone(),
                    cargo_features: ctx.cargo_features.clone(),
                },
                tier,
                only_check_id,
                UnitFilter::Only(check::Unit::Package),
            );
            analysed += 1;
            coverage::merge_runs(&mut outcomes, run.outcomes);
            // a member's note says which member it is about: two members can set aside different counts, or the same one
            for note in run.notes {
                let note = format!("{}: {note}", member.name);
                if !notes.contains(&note) {
                    notes.push(note);
                }
            }
            if !run.errors.is_empty() {
                with_errors += 1;
                failed_members.push(member.name.clone());
            }
            for mut waiver in run.waived {
                waiver.finding.member = Some(member.name.clone());
                waived.push(waiver);
            }
            for mut finding in run.findings {
                if finding.check_id == suppression::ALLOWLIST_CHECK_ID
                    && !judged.insert(allowlist_key(&finding))
                {
                    continue;
                }
                finding.member = Some(member.name.clone());
                findings.push(finding);
            }
            // when a restore failed for good the session's message replaces the member's own errors: it is the cause
            if let Some(why) = session.poison_message() {
                let rest: Vec<&str> = members[index + 1..]
                    .iter()
                    .map(|m| m.name.as_str())
                    .collect();
                errors.push(format!(
                    "{}: {why}; not analysed: {}",
                    member.name,
                    if rest.is_empty() {
                        "(no more members)".to_string()
                    } else {
                        rest.join(", ")
                    }
                ));
                with_errors += 1;
                if !failed_members.contains(&member.name) {
                    failed_members.push(member.name.clone());
                }
                return;
            }
            errors.extend(
                run.errors
                    .into_iter()
                    .map(|e| format!("{}: {e}", member.name)),
            );
        }
    });

    // The workspace root's crate-level `[reachability] public_api_crates` declarations are applied by each member's own run (see
    // `Allowlist::load_for_package`), so a run of one member by hand agrees with this one. A name that is no package of the workspace
    // can cover nothing in any of them, so it is reported here, where every package is known.
    if let Ok(root_list) = Allowlist::load(&root).map(Allowlist::crate_declarations) {
        let packages: Vec<&str> = members.iter().map(|m| m.name.as_str()).collect();
        let project = root
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_default();
        for entry in root_list.entries() {
            if entry
                .crate_scope
                .as_deref()
                .is_some_and(|name| !packages.contains(&name))
            {
                findings.push(suppression::unknown_crate(entry, &packages, &project));
            }
        }
    }

    WorkspaceRun {
        result: RunResult {
            findings,
            errors,
            outcomes,
            notes,
            waived,
        },
        members: analysed,
        members_with_errors: with_errors,
        members_failed: failed_members,
    }
}

/// What makes two allowlist-judgement findings the same one.
fn allowlist_key(finding: &Finding) -> (String, Option<String>, String) {
    (
        finding.project.clone(),
        finding.subject.clone(),
        finding.summary.clone(),
    )
}

/// Runs the built-in checks (see [`registered_checks`]) over the project at `ctx.project_root`: every check at or below
/// `tier`, or only the check named `only_check_id` (at any tier). See [`run_checks_with`] for what the host does with
/// what the checks return.
pub fn run_checks(ctx: &CheckContext, tier: Tier, only_check_id: Option<&str>) -> RunResult {
    run_checks_with(&registered_checks(), ctx, tier, only_check_id)
}

/// [`run_checks`] under a [`Profile`]: `Extended` also asks the language-neutral module for its rules, in the same run, so one
/// allowlist and one set of rule ids apply to all of them. `only_check_id` may then name one of those rules (`SUP-001`).
pub fn run_checks_in(
    profile: Profile,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
) -> RunResult {
    run_checks_in_with_tools(
        profile,
        &ToolEnv::from_environment(),
        ctx,
        tier,
        only_check_id,
    )
}

/// [`run_checks_in`] with the tools the delegated rules may use. `ToolEnv::from_environment()` (what [`run_checks_in`] passes)
/// has no consent to install, so a rule whose tool is not already installed is reported as not run; `.consent(Consent::Granted)`
/// lets the run install the pinned tool first.
pub fn run_checks_in_with_tools(
    profile: Profile,
    tools: &ToolEnv,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
) -> RunResult {
    run_checks_in_with_tools_skipping(profile, tools, ctx, tier, only_check_id, &[])
}

/// The built-in checks without the ones `skip` names, each as `(check id, why)`. A name that is no built-in check (a typo, or a rule
/// of a profile) is an error, never a quiet no-op; every skip is a note on the run, with its reason.
fn checks_without(skip: &[(String, String)]) -> Result<Vec<Box<dyn Check>>, String> {
    let checks = registered_checks();
    let ids: Vec<&str> = checks.iter().map(|c| c.id()).collect();
    for (id, _) in skip {
        if !ids.contains(&id.as_str()) {
            return Err(format!(
                "cannot skip \"{id}\": it is no built-in check; the checks are: {}",
                ids.join(", ")
            ));
        }
    }
    Ok(checks
        .into_iter()
        .filter(|c| !skip.iter().any(|(id, _)| id == c.id()))
        .collect())
}

fn skip_notes(skip: &[(String, String)]) -> impl Iterator<Item = String> + '_ {
    skip.iter()
        .map(|(id, why)| format!("{id} not run: skipped on request ({why})"))
}

/// [`run_checks_in_with_tools`] without the built-in checks named in `skip`, each as `(check id, why)`: the run does not call
/// them and says so in its notes, with the reason. A name that is not a built-in check is an error in the result.
pub fn run_checks_in_with_tools_skipping(
    profile: Profile,
    tools: &ToolEnv,
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    skip: &[(String, String)],
) -> RunResult {
    let checks = match checks_without(skip) {
        Ok(checks) => checks,
        Err(e) => return RunResult::new(Vec::new(), vec![e]),
    };
    let mut result = run_checks_over_in(
        profile,
        tools,
        &checks,
        ctx,
        tier,
        only_check_id,
        UnitFilter::Any,
    );
    result.notes.extend(skip_notes(skip));
    redact::finish(&mut result);
    result
}

/// Runs the checks you pass, the way [`run_checks`] runs the built-in ones: through the host, not by calling
/// [`Check::run`] yourself.
///
/// What the host does that a direct `check.run(ctx)` does not:
/// - **Validates every finding** ([`finding::Finding::validate`]). A finding whose summary claims an absence (contains
///   the whole word "zero", "no", "none", "missing", "unreachable" or "0"; "10 threads" and "casino" do not count)
///   without a `positive_control` is dropped and reported in `errors`.
/// - **Applies the project's allowlist**, read from `.coderipper.toml` in `ctx.project_root`. An entry waives a finding
///   only when its `check` and `file` equal the finding's `check_id` and `location.file`, and, when the entry gives them,
///   its `symbol` equals the finding's `subject` and the finding's `location.line` is within its `lines`. A check that
///   wants its findings to be waivable must set a location. Waived findings leave `findings` and are returned, with the
///   entry's reason, in [`RunResult::waived`].
/// - **Judges stale entries against the checks you pass.** An entry that suppressed nothing is reported as an `Info`
///   finding from the check id `allowlist`, and an entry naming a check that is not in `checks` is reported as an
///   unknown check. If you pass only your own check and the project's `.coderipper.toml` names built-in checks, each
///   of those entries is reported as unknown: pass the built-in checks too, or use a project without such entries.
/// - **Keeps the tier rule.** With `only_check_id = None`, a [`check::Tier::Sweep`] check does not run at
///   [`check::Tier::Fast`]; naming it with `only_check_id` runs it at any tier.
///
/// An error from one check (it could not run) is recorded in `errors` and does not stop the others.
///
/// ```
/// use coderipper::check::{Check, CheckContext, Network, Scope, Tier};
/// use coderipper::finding::{Confidence, Finding, Location, Severity};
///
/// /// Reports a `TODO.md` in the project root.
/// struct TodoFile;
///
/// impl Check for TodoFile {
///     fn id(&self) -> &'static str { "todo-file" }
///     fn scope(&self) -> Scope { Scope::Project }
///     fn network(&self) -> Network { Network::LocalOnly }
///     fn run(&self, ctx: &CheckContext) -> anyhow::Result<Vec<Finding>> {
///         if !ctx.project_root.join("TODO.md").exists() {
///             return Ok(Vec::new());
///         }
///         Ok(vec![Finding::new(
///             "todo-file", Severity::Low, Confidence::High, "demo",
///             "the project keeps a TODO.md", "TODO.md belongs in the issue tracker",
///         )
///         .location(Location::new("TODO.md", None))
///         .subject("TODO.md")])
///     }
/// }
///
/// let dir = tempfile::tempdir().unwrap();
/// std::fs::write(dir.path().join("TODO.md"), "- later\n").unwrap();
/// let ctx = CheckContext::new(dir.path());
/// let result = coderipper::run_checks_with(&[Box::new(TodoFile)], &ctx, Tier::Fast, None);
/// assert!(result.errors.is_empty());
/// assert_eq!(result.findings.len(), 1);
/// ```
pub fn run_checks_with(
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
) -> RunResult {
    let mut result = run_checks_over(checks, ctx, tier, only_check_id, UnitFilter::Any);
    redact::finish(&mut result);
    result
}

/// Why this list of checks and this `only_check_id` cannot be run, if they cannot: a named check that does not exist
/// (a typo must not read as a clean run) or two checks sharing an id (the id keys allowlist entries and `only_check_id`).
fn check_list_problem(
    checks: &[Box<dyn Check>],
    extra_rules: &[&str],
    only_check_id: Option<&str>,
) -> Option<String> {
    let mut ids: Vec<&str> = checks.iter().map(|c| c.id()).collect();
    if let Some(id) = ids
        .iter()
        .enumerate()
        .find_map(|(i, id)| ids[..i].contains(id).then_some(id))
    {
        return Some(format!(
            "the check id \"{id}\" is used by more than one check; ids must be unique"
        ));
    }
    ids.extend(extra_rules);
    let wanted = only_check_id?;
    (!ids.contains(&wanted)).then(|| {
        format!(
            "no check named \"{wanted}\"; the checks are: {}",
            ids.join(", ")
        )
    })
}

/// `run_checks` over an explicit list, so tests can drive the loop with fake checks.
fn run_checks_over(
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    units: UnitFilter,
) -> RunResult {
    run_checks_over_in(
        Profile::Classic,
        &ToolEnv::from_environment(),
        checks,
        ctx,
        tier,
        only_check_id,
        units,
    )
}

fn run_checks_over_in(
    profile: Profile,
    tools: &ToolEnv,
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    units: UnitFilter,
) -> RunResult {
    run_checks_over_in_counted(profile, tools, checks, ctx, tier, only_check_id, units).0
}

/// Whether `check` is asked for by this tier and `only_check_id` (a check named by id runs at any tier).
fn wanted_by(check: &dyn Check, tier: Tier, only_check_id: Option<&str>) -> bool {
    match only_check_id {
        Some(id) => check.id() == id,
        // Sweep mode runs everything; fast mode runs only fast-tier checks.
        None => !(check.tier() != tier && tier == Tier::Fast),
    }
}

/// [`run_checks_over_in`], how many crates were found and checked below a project root with no crate of its own (0 when the
/// root has one, which is the ordinary case), and how many of those crates reported an error.
fn run_checks_over_in_counted(
    profile: Profile,
    tools: &ToolEnv,
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    units: UnitFilter,
) -> (RunResult, usize, usize) {
    let extra = profile.extra_rules();
    if let Some(problem) = check_list_problem(checks, &extra, only_check_id) {
        return (RunResult::new(Vec::new(), vec![problem]), 0, 0);
    }
    // A project root with no `Cargo.toml` is "no Rust crate at this path", not a crate whose cargo failed. Only a plain run
    // decides this: a workspace run reaches a package only through a directory cargo already named.
    let rootless = matches!(units, UnitFilter::Any)
        && checks.iter().any(|c| c.requires_rust_crate())
        && !package::has_manifest(&ctx.project_root);
    let mut result = run_selected_checks(
        profile,
        tools,
        checks,
        ctx,
        tier,
        only_check_id,
        units,
        rootless,
    );
    if !rootless {
        return (result, 0, 0);
    }
    let wanted: Vec<&str> = checks
        .iter()
        .filter(|c| c.requires_rust_crate() && wanted_by(c.as_ref(), tier, only_check_id))
        .map(|c| c.id())
        .collect();
    if wanted.is_empty() {
        return (result, 0, 0);
    }
    let (below, crates, with_errors) =
        run_below_root(profile, tools, checks, ctx, tier, only_check_id, &wanted);
    result.findings.extend(below.findings);
    result.errors.extend(below.errors);
    result.notes.extend(below.notes);
    result.waived.extend(below.waived);
    coverage::merge_runs(&mut result.outcomes, below.outcomes);
    (result, crates, with_errors)
}

/// A project root with no crate of its own: finds the cargo workspaces the repository tracks below it and runs the
/// crate-reading checks in each (`wanted` names them), exactly as `--project <member directory>` would run them, so a
/// member's own `.coderipper.toml` applies. Says which crates it found, or that there is none: the Rust rules are then
/// `Skipped` in the coverage (a gap, never a failure). A crate that is found and cannot be read or built is an error.
fn run_below_root(
    profile: Profile,
    tools: &ToolEnv,
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    wanted: &[&str],
) -> (RunResult, usize, usize) {
    let mut result = RunResult::new(Vec::new(), Vec::new());
    let (found, problems) = package::discover_below(&ctx.project_root);
    result.errors.extend(problems.iter().cloned());
    if found.is_empty() {
        let outcome = if problems.is_empty() {
            result.notes.push(format!(
                "{} not run: no Rust crate at this path (no Cargo.toml in {} or below it)",
                wanted.join(", "),
                ctx.project_root.display()
            ));
            coverage::RunOutcome::Skipped
        } else {
            coverage::RunOutcome::CouldNotRun
        };
        result
            .outcomes
            .extend(wanted.iter().map(|id| coverage::RuleRun::new(*id, outcome)));
        return (result, 0, 0);
    }

    let crates: usize = found.iter().map(|w| w.members.len()).sum();
    let listing: Vec<String> = found
        .iter()
        .flat_map(|w| &w.members)
        .map(|m| {
            let dir = package::relative_to(&ctx.project_root, &m.dir);
            let separator = if dir.ends_with('/') { "" } else { "/" };
            format!("{} ({dir}{separator}Cargo.toml)", m.name)
        })
        .collect();
    result.notes.push(format!(
        "no Cargo.toml at {}; found {} Rust crate(s) below it and checked each where it is: {}",
        ctx.project_root.display(),
        crates,
        listing.join(", ")
    ));

    let mut judged = std::collections::HashSet::new();
    let mut with_errors = 0;
    let mut absorb = |run: RunResult, member: Option<&str>, label: &str, dir: &str| {
        if !run.errors.is_empty() {
            with_errors += 1;
        }
        coverage::merge_runs(&mut result.outcomes, run.outcomes);
        for note in run.notes {
            // a crate's note says which crate it is about (see the workspace loop)
            let note = format!("{label}: {note}");
            if !result.notes.contains(&note) {
                result.notes.push(note);
            }
        }
        for mut waiver in run.waived {
            waiver.finding.member = member.map(str::to_string);
            result.waived.push(waiver);
        }
        for mut finding in run.findings {
            // one allowlist file, one stale-entry judgement: a root package is both a repository unit and a member, and two
            // crates can share a directory name, so the key carries the directory
            if finding.check_id == suppression::ALLOWLIST_CHECK_ID
                && !judged.insert((dir.to_string(), allowlist_key(&finding)))
            {
                continue;
            }
            finding.member = member.map(str::to_string);
            result.findings.push(finding);
        }
        result
            .errors
            .extend(run.errors.into_iter().map(|e| format!("{label}: {e}")));
    };
    let any_at = |unit: check::Unit| {
        checks
            .iter()
            .any(|c| c.unit() == unit && wanted.contains(&c.id()))
    };
    for workspace in &found {
        let label = package::relative_to(&ctx.project_root, &workspace.root);
        if any_at(check::Unit::Repository) {
            let run = run_checks_over_in(
                profile,
                tools,
                checks,
                &CheckContext {
                    project_root: workspace.root.clone(),
                    portfolio_root: ctx.portfolio_root.clone(),
                    cargo_features: ctx.cargo_features.clone(),
                },
                tier,
                only_check_id,
                UnitFilter::RustOnly(check::Unit::Repository),
            );
            absorb(
                run,
                None,
                label.trim_end_matches('/'),
                &workspace.root.display().to_string(),
            );
        }
        if any_at(check::Unit::Package) {
            for member in &workspace.members {
                let run = run_checks_over_in(
                    profile,
                    tools,
                    checks,
                    &CheckContext {
                        project_root: member.dir.clone(),
                        portfolio_root: ctx.portfolio_root.clone(),
                        cargo_features: ctx.cargo_features.clone(),
                    },
                    tier,
                    only_check_id,
                    UnitFilter::RustOnly(check::Unit::Package),
                );
                absorb(
                    run,
                    Some(&member.name),
                    &member.name,
                    &member.dir.display().to_string(),
                );
            }
        }
    }
    (result, crates, with_errors)
}

#[allow(
    clippy::too_many_arguments,
    reason = "each argument is one independent input of a run; a parameter struct would only rename them"
)]
fn run_selected_checks(
    profile: Profile,
    tools: &ToolEnv,
    checks: &[Box<dyn Check>],
    ctx: &CheckContext,
    tier: Tier,
    only_check_id: Option<&str>,
    units: UnitFilter,
    rootless: bool,
) -> RunResult {
    let mut extra = profile.extra_rules();
    // Classic's one extra rule reads HEAD. A project that is not a git repository with a commit has nothing for it to read,
    // and a classic run must not start failing there (the extended profile does say so: the neutral rules error on it).
    if profile == Profile::Classic
        && !conformance::git_command(&ctx.project_root)
            .args(["rev-parse", "--verify", "-q", "HEAD"])
            .output()
            .is_ok_and(|o| o.status.success())
    {
        extra.clear();
    }
    // The checks to run, decided here (the host chooses what is in scope), then asked of the Rust module as one request.
    let mut selected: Vec<String> = checks
        .iter()
        .filter(|check| match units {
            UnitFilter::Only(unit) => check.unit() == unit,
            UnitFilter::RustOnly(unit) => check.unit() == unit && check.requires_rust_crate(),
            UnitFilter::Any => true,
        })
        // no crate at the root: the crate-reading checks are not asked of it (see `run_below_root`)
        .filter(|check| !(rootless && check.requires_rust_crate()))
        .filter(|check| wanted_by(check.as_ref(), tier, only_check_id))
        .map(|check| check.id().to_string())
        .collect();
    let unit = match units {
        UnitFilter::Only(unit) | UnitFilter::RustOnly(unit) => Some(unit),
        UnitFilter::Any => None,
    };
    // A rule that asks a service over the network (the advisory database) is a sweep-tier rule, like a network check: a fast run
    // does not take it, and one that names it is asking for it, so it is given the network.
    let needs_network = |id: &str| {
        catalog::Catalog::builtin()
            .get(id)
            .is_some_and(|rule| rule.network() == check::Network::NetworkRequired)
    };
    // The neutral rules judge the whole repository, so they run in the repository pass (and in a plain run), once.
    if !matches!(
        units,
        UnitFilter::Only(check::Unit::Package) | UnitFilter::RustOnly(_)
    ) {
        selected.extend(
            extra
                .iter()
                .filter(|id| match only_check_id {
                    Some(only) => only == **id,
                    None => tier == Tier::Sweep || !needs_network(id),
                })
                .map(|id| (*id).to_string()),
        );
    }
    let tier = if only_check_id.is_some_and(|id| extra.contains(&id) && needs_network(id)) {
        Tier::Sweep
    } else {
        tier
    };
    let mut registered: Vec<&str> = checks.iter().map(|c| c.id()).collect();
    registered.extend(&extra);
    // Over the built-in checks, a name the allowlist may use is any rule of this build, not only the profile's: an entry for a rule
    // another profile runs is not a typo. Over a list of the caller's own checks the entries are judged against that list alone.
    let built_in: Vec<String> = registered_checks()
        .iter()
        .map(|c| c.id().to_string())
        .collect();
    if !checks.is_empty()
        && checks
            .iter()
            .all(|c| built_in.iter().any(|id| id == c.id()))
    {
        for id in Profile::Extended.extra_rules() {
            if !registered.contains(&id) {
                registered.push(id);
            }
        }
    }
    let rust = module::RustModule::new(checks);
    let neutral = module::NeutralModule::new();
    let delegated = module::DelegatedModule::new(tools.clone());
    let composite = module::Composite::new(vec![&rust, &neutral, &delegated]);
    let module: &dyn module::Module = &composite;
    run_module_over(
        module,
        ctx,
        tier,
        unit,
        selected,
        &registered,
        module::Limits::default(),
    )
}

/// Asks `module` to check `rules` and turns what it says into a [`RunResult`]: the findings are validated and
/// suppressed by the allowlist exactly as a built-in check's are, and a rule that gave no verdict is an entry in `errors`.
/// `registered` is every rule id the allowlist may name (for the stale-entry judgement).
fn run_module_over(
    module: &dyn module::Module,
    ctx: &CheckContext,
    tier: Tier,
    unit: Option<check::Unit>,
    rules: Vec<String>,
    registered: &[&str],
    limits: module::Limits,
) -> RunResult {
    let mut findings = Vec::new();
    let mut errors = Vec::new();
    let mut outcomes = Vec::new();
    let mut notes = Vec::new();

    // A malformed allowlist must not swallow the findings: report it, and run unsuppressed.
    let allowlist = Allowlist::load_for_package(&ctx.project_root).unwrap_or_else(|e| {
        errors.push(format!("allowlist: {e}"));
        Allowlist::empty()
    });
    let mut suppression = Suppression::for_project(&allowlist, &ctx.project_root);

    let request = module::Request::new(ctx, unit, tier, rules, limits);
    let reconciled = module::reconcile(&request, module.check(&request));

    for outcome in reconciled.rules {
        let skipped = matches!(
            outcome.status,
            module::RuleStatus::Skipped { .. } | module::RuleStatus::Unavailable { .. }
        );
        let completed = match &outcome.status {
            module::RuleStatus::Ran => true,
            module::RuleStatus::Skipped { .. } => false,
            module::RuleStatus::Unavailable { detail } => {
                notes.push(format!("{} not run: {detail}", outcome.rule));
                false
            }
            module::RuleStatus::Error { kind, detail } => {
                errors.push(match kind {
                    module::ErrorKind::Internal => {
                        format!("{} failed to run: {detail}", outcome.rule)
                    }
                    kind => format!("{} failed to run ({kind}): {detail}", outcome.rule),
                });
                false
            }
        };
        let mut valid = Vec::new();
        let mut all_valid = true;
        for f in outcome.findings {
            match f.validate() {
                Ok(f) => valid.push(f),
                Err(e) => {
                    all_valid = false;
                    errors.push(format!("{}: {e}", outcome.rule));
                }
            }
        }
        // A check that produced an invalid finding, or did not complete, is not trusted to have completed, so its
        // allowlist entries are not judged either.
        if completed && all_valid {
            suppression.mark_completed(&outcome.rule, valid.len());
        }
        notes.extend(outcome.notes);
        let kept = suppression.apply(valid);
        outcomes.push(coverage::RuleRun::new(
            &outcome.rule,
            if skipped {
                coverage::RunOutcome::Skipped
            } else if !(completed && all_valid) {
                coverage::RunOutcome::CouldNotRun
            } else if kept.is_empty() {
                coverage::RunOutcome::Clean
            } else {
                coverage::RunOutcome::Findings(kept.len())
            },
        ));
        findings.extend(kept);
    }
    errors.extend(reconciled.run_errors);
    if suppression.excluded() > 0 {
        notes.push(format!(
            "{} finding(s) in this repository's own conformance fixtures (conformance/<rule>/<variant>/, each with an expect.toml) were not reported: a fixture is defective on purpose",
            suppression.excluded()
        ));
    }

    let project = ctx
        .project_root
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    findings.extend(suppression.stale_findings(registered, &project));

    RunResult {
        findings,
        errors,
        outcomes,
        notes,
        waived: suppression.take_waived(),
    }
}

/// Runs a [`module::Module`] (an [`module::ExternalModule`] over a child process, or your own) over the project at
/// `ctx.project_root`, the way [`run_checks`] runs the built-in checks: findings are validated and the project's
/// allowlist applied, and a rule that gave no verdict (the module crashed, hung, printed too much, printed garbage, or
/// said nothing about it) is an entry in `errors`, never a silent absence of findings.
///
/// A rule the module skips as not applicable is a coverage gap, not a failure: it adds neither a finding nor an error, and
/// this result cannot yet say which rules were skipped (the coverage report, a later phase, will).
///
/// It asks for every rule the module's hello claims, at `tier`. Choosing rules by tier and unit needs the rule catalog,
/// which is not built yet.
pub fn run_module(
    module: &dyn module::Module,
    ctx: &CheckContext,
    tier: Tier,
    limits: module::Limits,
) -> RunResult {
    let mut result = run_module_unredacted(module, ctx, tier, limits);
    redact::finish(&mut result);
    result
}

fn run_module_unredacted(
    module: &dyn module::Module,
    ctx: &CheckContext,
    tier: Tier,
    limits: module::Limits,
) -> RunResult {
    let hello = match module.describe() {
        Ok(hello) => hello,
        Err(e) => return RunResult::new(Vec::new(), vec![format!("the module's hello: {e}")]),
    };
    if let Some(problem) = hello.problem() {
        return RunResult::new(Vec::new(), vec![format!("the module's hello: {problem}")]);
    }
    let claimed: Vec<&str> = hello
        .rules
        .iter()
        .filter(|r| r.status != crate::module::ClaimStatus::NotApplicable)
        .map(|r| r.id.as_str())
        .collect();
    let registered: Vec<&str> = hello.rules.iter().map(|r| r.id.as_str()).collect();
    run_module_over(
        module,
        ctx,
        tier,
        None,
        claimed.iter().map(|id| id.to_string()).collect(),
        &registered,
        limits,
    )
}

