export function isTenth(x: number): boolean {
  return x === 0.1;
}

export function moved(a: number): boolean {
  return 2.5 != a;
}

export function negative(x: number): boolean {
  return x === -0.5;
}

export function wrapped(x: number): boolean {
  return (0.25) !== x;
}
