//! Does two things at build time. Generates the rule-id constants from `rules/*.toml` (see `rule_ids`). Fails the build when the shipped `src/tools/tools.lock` breaks the lock rules (a bad hash, an unsafe name, a source scheme
//! the installer refuses, a duplicate entry). The rules are `src/tools/lock_rules.rs`, the same file the run-time parser uses.

#[path = "src/tools/lock_rules.rs"]
mod lock_rules;

fn main() {
    rule_ids();
    println!("cargo:rerun-if-changed=src/tools/tools.lock");
    println!("cargo:rerun-if-changed=src/tools/lock_rules.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string("src/tools/tools.lock").expect("read src/tools/tools.lock");
    if let Err(problem) = check_lock(&text) {
        panic!("src/tools/tools.lock is invalid: {problem}");
    }
}

/// Writes `$OUT_DIR/rule_ids.rs`: one `pub const` per rule id in `rules/*.toml` (`WSP-001` -> `WSP_001`, `conflict-marker` ->
/// `CONFLICT_MARKER`). A check names its rule through these, so a typo is a compile error, not a rule that silently never matches.
fn rule_ids() {
    println!("cargo:rerun-if-changed=rules");
    let mut files: Vec<_> = std::fs::read_dir("rules")
        .expect("read rules/")
        .map(|e| e.expect("read a rules/ entry").path())
        .filter(|p| p.extension().is_some_and(|e| e == "toml"))
        .collect();
    files.sort();
    let mut consts: Vec<(String, String)> = Vec::new();
    for file in files {
        println!("cargo:rerun-if-changed={}", file.display());
        let text = std::fs::read_to_string(&file).expect("read a rules file");
        let table: toml::Table = text
            .parse()
            .unwrap_or_else(|e| panic!("{}: {e}", file.display()));
        let rules = table
            .get("rule")
            .and_then(toml::Value::as_array)
            .cloned()
            .unwrap_or_default();
        for rule in rules {
            let id = rule
                .get("id")
                .and_then(toml::Value::as_str)
                .unwrap_or_else(|| panic!("{}: a rule has no id", file.display()));
            let name: String = id
                .chars()
                .map(|c| {
                    if c.is_ascii_alphanumeric() {
                        c.to_ascii_uppercase()
                    } else {
                        '_'
                    }
                })
                .collect();
            assert!(
                name.starts_with(|c: char| c.is_ascii_uppercase()),
                "{}: rule id {id:?} does not make an identifier",
                file.display()
            );
            assert!(
                !consts.iter().any(|(n, _)| *n == name),
                "{}: rule id {id:?} collides with another",
                file.display()
            );
            consts.push((name, id.to_string()));
        }
    }
    let mut out = String::from(
        "// Generated by build.rs from rules/*.toml. Do not edit.
",
    );
    for (name, id) in &consts {
        out.push_str(&format!("pub const {name}: &str = {id:?};\n"));
    }
    let dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(std::path::Path::new(&dir).join("rule_ids.rs"), out).expect("write rule_ids.rs");
}

fn check_lock(text: &str) -> Result<(), String> {
    let table: toml::Table = text.parse().map_err(|e| format!("not TOML: {e}"))?;
    let mut seen: Vec<(String, String)> = Vec::new();
    for (key, value) in &table {
        if key != "tool" {
            return Err(format!("unknown top-level key {key:?}"));
        }
        let entries = value.as_array().ok_or("`tool` is not an array of tables")?;
        for entry in entries {
            let entry = entry.as_table().ok_or("a `tool` entry is not a table")?;
            let text = |k: &str| entry.get(k).and_then(toml::Value::as_str);
            let need = |k: &str| text(k).ok_or(format!("an entry lacks the string `{k}`"));
            let (name, version, platform) = (need("name")?, need("version")?, need("platform")?);
            let label = format!("{name} {version}");
            lock_rules::check(&lock_rules::Fields {
                name,
                version,
                platform,
                source: need("source")?,
                sha256: need("sha256")?,
                licence: need("licence")?,
                file: text("file"),
                archive: text("archive"),
                member: text("member"),
                file_sha256: text("file_sha256"),
            })
            .map_err(|what| format!("{label}: {what}"))?;
            let id = (name.to_ascii_lowercase(), platform.to_string());
            if seen.contains(&id) {
                return Err(format!("{label}: two entries for {platform}"));
            }
            seen.push(id);
        }
    }
    Ok(())
}
